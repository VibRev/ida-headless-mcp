/// One NUL-terminated string read out of memory.
///
/// Unlike the `strings` tools this reads whatever bytes are at the address; it
/// does not require IDA to have detected a string there.
#[derive(Debug, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct StringReadResult {
    /// Address read from, hex-formatted.
    pub address: String,
    /// Decoded text, lossy UTF-8, up to the first NUL.
    pub string: String,
    /// Length in bytes up to the NUL.
    pub length: usize,
    /// The same bytes, lowercase hex, no separators.
    pub bytes: String,
}

