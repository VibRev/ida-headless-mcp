/// One converted integer, or the reason the input could not be parsed.
#[derive(Debug, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct IntConvertEntry {
    /// The input string exactly as supplied.
    pub input: String,
    /// Parsed value as a JSON number.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub value: Option<u64>,
    /// Decimal rendering.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub dec: Option<String>,
    /// Hexadecimal rendering with a `0x` prefix.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub hex: Option<String>,
    /// Binary rendering with a `0b` prefix.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bin: Option<String>,
    /// Little-endian bytes, hex, trailing zero bytes trimmed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bytes_le: Option<String>,
    /// Big-endian bytes, hex, leading zero bytes trimmed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bytes_be: Option<String>,
    /// Little-endian bytes rendered as ASCII, `.` for unprintable bytes.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub ascii: Option<String>,
    /// Why the input could not be parsed; absent on success.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
}

/// `int_convert` output.
#[derive(Debug, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct IntConvertOutput {
    /// One entry per input, in the order supplied.
    pub results: Vec<IntConvertEntry>,
}
